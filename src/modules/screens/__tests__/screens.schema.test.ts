import { describe, expect, it } from 'vitest';
import { createScreenSchema, updateScreenSchema } from '../screens.schema.js';
import { screenInput } from './screens.fixtures.js';

describe('createScreenSchema', () => {
  it('accepts a valid screen', () => {
    expect(createScreenSchema.safeParse(screenInput).success).toBe(true);
  });

  it.each([
    { reason: 'only whitespace', name: '   ' },
    { reason: 'blank', name: '' },
    { reason: 'more than 100 characters long', name: 'a'.repeat(101) },
    { reason: 'not a string', name: 1 },
  ])('rejects a name that is $reason', ({ name }) => {
    const result = createScreenSchema.safeParse({ name });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]?.path).toEqual(['name']);
  });

  it.each([1, 100])('accepts a name of %i characters', (length) => {
    expect(createScreenSchema.safeParse({ name: 'a'.repeat(length) }).success).toBe(true);
  });

  it('trims the name in the parsed screen', () => {
    const result = createScreenSchema.safeParse({ name: `  ${screenInput.name}  ` });

    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data).toEqual(screenInput);
    }
  });

  it('rejects a missing name', () => {
    const result = createScreenSchema.safeParse({});

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]?.path).toEqual(['name']);
  });

  // venueId comes from the path; id is generated by the database.
  it.each(['venueId', 'id'])('rejects %s in the body', (field) => {
    const result = createScreenSchema.safeParse({
      ...screenInput,
      [field]: '019a0000-0000-7000-8000-000000000101',
    });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]).toMatchObject({ code: 'unrecognized_keys', keys: [field] });
  });
});

describe('updateScreenSchema', () => {
  it('accepts a new name and trims it', () => {
    const result = updateScreenSchema.safeParse({ name: '  Screen 2  ' });

    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data).toEqual({ name: 'Screen 2' });
    }
  });

  it('rejects an empty update', () => {
    expect(updateScreenSchema.safeParse({}).success).toBe(false);
  });

  it('rejects a blank name', () => {
    const result = updateScreenSchema.safeParse({ name: '   ' });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]?.path).toEqual(['name']);
  });

  // A screen cannot move to another venue.
  it.each(['venueId', 'id', 'unknown'])('rejects %s in the body', (field) => {
    const result = updateScreenSchema.safeParse({ [field]: 'value' });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]).toMatchObject({ code: 'unrecognized_keys', keys: [field] });
  });
});
