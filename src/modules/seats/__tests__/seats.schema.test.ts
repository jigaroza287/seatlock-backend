import { describe, expect, it } from 'vitest';
import { createSeatSchema, listSeatQuerySchema, updateSeatSchema } from '../seats.schema.js';
import { seatInput } from './seats.fixtures.js';

describe('createSeatSchema', () => {
  it('accepts a valid seat', () => {
    expect(createSeatSchema.safeParse(seatInput).success).toBe(true);
  });

  it('trims and uppercases the row label', () => {
    const result = createSeatSchema.safeParse({ ...seatInput, rowLabel: '  aa  ' });

    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.rowLabel).toBe('AA');
    }
  });

  it.each([
    { reason: 'only whitespace', rowLabel: '   ' },
    { reason: 'blank', rowLabel: '' },
    { reason: 'more than 10 characters long', rowLabel: 'A'.repeat(11) },
    { reason: 'not a string', rowLabel: 1 },
  ])('rejects a row label that is $reason', ({ rowLabel }) => {
    const result = createSeatSchema.safeParse({ ...seatInput, rowLabel });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]?.path).toEqual(['rowLabel']);
  });

  it.each([1, 10])('accepts a row label of %i characters', (length) => {
    expect(createSeatSchema.safeParse({ ...seatInput, rowLabel: 'A'.repeat(length) }).success).toBe(
      true
    );
  });

  it.each([
    { reason: '0', seatNumber: 0 },
    { reason: 'above 100', seatNumber: 101 },
    { reason: 'not an integer', seatNumber: 1.5 },
    { reason: 'a string', seatNumber: '1' },
  ])('rejects a seat number that is $reason', ({ seatNumber }) => {
    const result = createSeatSchema.safeParse({ ...seatInput, seatNumber });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]?.path).toEqual(['seatNumber']);
  });

  it.each([1, 100])('accepts seat number %i', (seatNumber) => {
    expect(createSeatSchema.safeParse({ ...seatInput, seatNumber }).success).toBe(true);
  });

  it.each(['standard', 'premium', 'recliner'])('accepts category %s', (category) => {
    expect(createSeatSchema.safeParse({ ...seatInput, category }).success).toBe(true);
  });

  it('rejects an unknown category', () => {
    const result = createSeatSchema.safeParse({ ...seatInput, category: 'vip' });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]?.path).toEqual(['category']);
  });

  it.each(['rowLabel', 'seatNumber', 'category'])('rejects a missing %s', (field) => {
    const result = createSeatSchema.safeParse({ ...seatInput, [field]: undefined });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]?.path).toEqual([field]);
  });

  // screenId comes from the path; id is generated by the database.
  it.each(['screenId', 'id'])('rejects %s in the body', (field) => {
    const result = createSeatSchema.safeParse({
      ...seatInput,
      [field]: '019a0000-0000-7000-8000-000000000201',
    });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]).toMatchObject({ code: 'unrecognized_keys', keys: [field] });
  });
});

describe('updateSeatSchema', () => {
  it.each([
    { field: 'rowLabel', body: { rowLabel: ' b ' }, expected: { rowLabel: 'B' } },
    { field: 'seatNumber', body: { seatNumber: 2 }, expected: { seatNumber: 2 } },
    { field: 'category', body: { category: 'premium' }, expected: { category: 'premium' } },
  ])('accepts $field alone', ({ body, expected }) => {
    const result = updateSeatSchema.safeParse(body);

    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data).toEqual(expected);
    }
  });

  it('rejects an empty update', () => {
    expect(updateSeatSchema.safeParse({}).success).toBe(false);
  });

  it('rejects a blank row label', () => {
    const result = updateSeatSchema.safeParse({ rowLabel: '   ' });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]?.path).toEqual(['rowLabel']);
  });

  // A seat cannot move to another screen.
  it.each(['screenId', 'id', 'unknown'])('rejects %s in the body', (field) => {
    const result = updateSeatSchema.safeParse({ [field]: 'value' });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]).toMatchObject({ code: 'unrecognized_keys', keys: [field] });
  });
});

describe('listSeatQuerySchema', () => {
  it('applies the default pagination', () => {
    expect(listSeatQuerySchema.parse({})).toEqual({ limit: 20, offset: 0 });
  });

  it('accepts a category filter', () => {
    expect(listSeatQuerySchema.parse({ category: 'premium' })).toEqual({
      limit: 20,
      offset: 0,
      category: 'premium',
    });
  });

  it('rejects an unknown category filter', () => {
    const result = listSeatQuerySchema.safeParse({ category: 'vip' });

    expect(result.success).toBe(false);
    expect(result.error?.issues[0]?.path).toEqual(['category']);
  });
});
